-- Part A.2 — Schema definitions (PostgreSQL 15+)
-- System of record for the Supplier Watch model. Column meanings: see 01_entity_model.md.
--
-- Conventions
--   * fact_ tables for S1/S2/S3 are SCD Type 2: (natural_key, valid_from) is the key,
--     valid_to = 'infinity' while current, is_current mirrors that for easy filtering.
--     Rows are never UPDATEd except to close valid_to / flip is_current.
--   * valid_from / valid_to mean "when OUR PLATFORM showed this version", not agency dates.
--   * *_as_published columns keep the agency's text verbatim; normalised columns may be
--     recomputed on reprocessing without touching raw files.

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- non-overlap constraints on SCD2 ranges
CREATE EXTENSION IF NOT EXISTS pg_trgm;      -- name/address similarity for matching candidates

-- ============================================================================
-- LINEAGE
-- ============================================================================
-- One row per batch file received (S1/S2/S3). Stream events are not tracked here: duplicates are
-- rejected by the fact table's primary key and replay reads the raw event archive in S3.
CREATE TABLE ingest_batch (
    batch_id        uuid PRIMARY KEY,
    source_code     text NOT NULL CHECK (source_code IN ('S1','S2','S3')),
    received_at     timestamptz NOT NULL,                  -- becomes valid_from on the fact versions it introduces
    s3_path         text NOT NULL,                         -- immutable raw file
    row_count       int,
    status          text NOT NULL CHECK (status IN ('RECEIVED','PARSED','LOADED','FAILED','QUARANTINED')),
    parser_version  text NOT NULL,
    dq_checks       jsonb
);

-- ============================================================================
-- DIMENSIONS
-- ============================================================================
CREATE TABLE dim_site (
    site_key      text PRIMARY KEY,                        -- 'S-000001', generated by us
    site_name     text NOT NULL,
    country_code  char(2),
    city          text,
    address       text,
    is_active     boolean NOT NULL DEFAULT true,           -- false once merged into another site
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dim_site_name_trgm    ON dim_site USING gin (site_name gin_trgm_ops);
CREATE INDEX dim_site_address_trgm ON dim_site USING gin (address gin_trgm_ops);
CREATE INDEX dim_site_block        ON dim_site (country_code, city);     -- blocking key for matching

-- The bridge: agency identifier -> our site, as SCD2.
-- Steward actions (merge, split, link, unlink) are recorded on the rows they open/close:
-- every row touched by one action shares a decision_group_id, so a split can find and reverse a merge.
CREATE TABLE dim_site_identifier (
    identifier_type         text NOT NULL CHECK (identifier_type IN ('FEI','EU_SITE_REF','LETTER_ID','WATCH_ID')),
    identifier_value        text NOT NULL,
    valid_from              timestamptz NOT NULL DEFAULT now(),
    valid_to                timestamptz NOT NULL DEFAULT 'infinity',
    is_current              boolean NOT NULL DEFAULT true,
    site_key                text NOT NULL REFERENCES dim_site,
    match_method            text NOT NULL CHECK (match_method IN ('EXACT_ID','RULE','FUZZY','STEWARD')),
    match_score             numeric(4,3),
    match_evidence          jsonb,
    matching_rules_version  text NOT NULL,
    decided_by              text NOT NULL,                 -- steward user id, or 'system:er-v3'
    decision_reason         text,                          -- free text; NULL for automatic matches
    decision_group_id       uuid,                          -- shared by all rows one steward action touched
    PRIMARY KEY (identifier_type, identifier_value, valid_from),
    -- one identifier belongs to exactly one site at any instant
    EXCLUDE USING gist (identifier_type WITH =, identifier_value WITH =, tstzrange(valid_from, valid_to) WITH &&)
);
CREATE INDEX dim_site_identifier_current_by_id   ON dim_site_identifier (identifier_type, identifier_value) WHERE is_current;
CREATE INDEX dim_site_identifier_current_by_site ON dim_site_identifier (site_key) WHERE is_current;

CREATE TABLE match_review_queue (
    review_id         uuid PRIMARY KEY,
    identifier_type   text NOT NULL,
    identifier_value  text NOT NULL,
    candidate_sites   jsonb NOT NULL,                      -- [{site_key, score, evidence}, ...]
    status            text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','LINKED','NEW_SITE','REJECTED')),
    opened_at         timestamptz NOT NULL DEFAULT now(),
    reviewed_by       text,
    reviewed_at       timestamptz,
    decision_group_id uuid                                 -- the bridge rows the review produced
);
CREATE UNIQUE INDEX match_review_queue_open ON match_review_queue (identifier_type, identifier_value) WHERE status = 'OPEN';

CREATE TABLE dim_customer (
    customer_id    text PRIMARY KEY,
    customer_name  text NOT NULL
);

CREATE TABLE dim_watchlist_entry (
    watch_id               bigint NOT NULL,                -- from the customer app
    valid_from             timestamptz NOT NULL,
    valid_to               timestamptz NOT NULL DEFAULT 'infinity',
    is_current             boolean NOT NULL DEFAULT true,
    customer_id            text NOT NULL REFERENCES dim_customer,
    customer_supplier_ref  text,
    supplier_name_as_typed text NOT NULL,
    country_as_typed       text,
    fei_number_as_typed    text,
    is_active              boolean NOT NULL,               -- false after a CDC delete
    cdc_timestamp          bigint NOT NULL,                -- ts_ms; older events are ignored
    PRIMARY KEY (watch_id, valid_from),
    EXCLUDE USING gist (watch_id WITH =, tstzrange(valid_from, valid_to) WITH &&)
);
CREATE INDEX dim_watchlist_entry_by_customer ON dim_watchlist_entry (customer_id) WHERE is_current AND is_active;

-- ============================================================================
-- FACTS
-- ============================================================================

-- S1: FDA inspection classifications. Weekly full snapshot; versions come from diffing snapshots.
CREATE TABLE fact_inspection (
    inspection_id                     text NOT NULL,
    valid_from                        timestamptz NOT NULL,
    valid_to                          timestamptz NOT NULL DEFAULT 'infinity',
    is_current                        boolean NOT NULL DEFAULT true,
    record_status                     text NOT NULL CHECK (record_status IN ('ACTIVE','RETRACTED')),
    batch_id                          uuid NOT NULL REFERENCES ingest_batch,
    fei_number                        text NOT NULL,
    firm_name_as_published            text,
    city                              text,
    country_code                      char(2),
    inspection_end_date               date,
    inspection_end_date_as_published  text,
    classification                    text CHECK (classification IN ('NAI','VAI','OAI')),
    product_type                      text,
    published_date                    date,
    PRIMARY KEY (inspection_id, valid_from),
    EXCLUDE USING gist (inspection_id WITH =, tstzrange(valid_from, valid_to) WITH &&)
);
CREATE INDEX fact_inspection_current_by_fei ON fact_inspection (fei_number) WHERE is_current;
CREATE INDEX fact_inspection_by_end_date    ON fact_inspection (inspection_end_date);

-- S2: EU GMP certificates and non-compliance reports. Monthly export; same diff-based SCD2.
CREATE TABLE fact_gmp_document (
    doc_ref                  text NOT NULL,
    valid_from               timestamptz NOT NULL,
    valid_to                 timestamptz NOT NULL DEFAULT 'infinity',
    is_current               boolean NOT NULL DEFAULT true,
    record_status            text NOT NULL CHECK (record_status IN ('ACTIVE','RETRACTED')),
    batch_id                 uuid NOT NULL REFERENCES ingest_batch,
    doc_type                 text CHECK (doc_type IN ('GMP_CERTIFICATE','NON_COMPLIANCE')),
    site_ref                 text NOT NULL,
    site_name_as_published   text,
    address_as_published     text,
    country_code             char(2),
    issuing_authority        text,
    inspection_end_date      date,
    issued_date              date,
    status                   text CHECK (status IN ('ACTIVE','WITHDRAWN')),   -- the agency's status
    PRIMARY KEY (doc_ref, valid_from),
    EXCLUDE USING gist (doc_ref WITH =, tstzrange(valid_from, valid_to) WITH &&)
);
CREATE INDEX fact_gmp_document_current_by_site_ref ON fact_gmp_document (site_ref) WHERE is_current;

-- S3: Warning letters. Body text stays in S3.
CREATE TABLE fact_warning_letter (
    letter_id                        text NOT NULL,
    valid_from                       timestamptz NOT NULL,
    valid_to                         timestamptz NOT NULL DEFAULT 'infinity',
    is_current                       boolean NOT NULL DEFAULT true,
    record_status                    text NOT NULL CHECK (record_status IN ('ACTIVE','RETRACTED')),
    batch_id                         uuid NOT NULL REFERENCES ingest_batch,
    fei_number                       text,                 -- usually NULL
    recipient_firm_as_published      text,
    recipient_address_as_published   text,
    country_code                     char(2),
    issue_date                       date,
    subject                          text,
    body_s3_path                     text NOT NULL,
    source_url                       text,
    nlp_status                       text NOT NULL DEFAULT 'PENDING' CHECK (nlp_status IN ('PENDING','DONE','FAILED')),
    PRIMARY KEY (letter_id, valid_from),
    EXCLUDE USING gist (letter_id WITH =, tstzrange(valid_from, valid_to) WITH &&)
);

CREATE TABLE fact_letter_tag (
    letter_id          text NOT NULL,
    nlp_model_version  text NOT NULL,
    tag                text NOT NULL,
    confidence         numeric(4,3),
    tagged_at          timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (letter_id, nlp_model_version, tag)
);

-- S4: Enforcement actions. Versioned by the agency; current state = highest action_version.
CREATE TABLE fact_enforcement_action (
    action_id       text NOT NULL,
    action_version  int  NOT NULL,
    event_id        text NOT NULL,                         -- traceability to the S3 event archive
    operation       text NOT NULL CHECK (operation IN ('UPSERT','RETRACT')),
    action_type     text,
    agency          text,
    fei_number      text,                                  -- NULL on a bare RETRACT
    firm_name       text,                                  -- v1 'firm' and v2 'firm_name' both land here
    country_code    char(2),
    product_codes   jsonb,                                 -- v2 only
    effective_date  date,
    event_time      timestamptz NOT NULL,
    loaded_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (action_id, action_version)
);
CREATE INDEX fact_enforcement_action_by_fei ON fact_enforcement_action (fei_number);

CREATE TABLE fact_alert (
    alert_id        uuid PRIMARY KEY,
    customer_id     text   NOT NULL REFERENCES dim_customer,
    watch_id        bigint NOT NULL,
    site_key        text   NOT NULL REFERENCES dim_site,
    action_id       text   NOT NULL,
    action_version  int    NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    delivered_at    timestamptz,
    UNIQUE (watch_id, action_id, action_version)           -- idempotent fan-out
);

-- ============================================================================
-- TENANT ISOLATION (enforced in the database, not only in app code)
-- ============================================================================
ALTER TABLE dim_watchlist_entry ENABLE ROW LEVEL SECURITY;
ALTER TABLE fact_alert          ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_watchlist ON dim_watchlist_entry USING (customer_id = current_setting('app.customer_id', true));
CREATE POLICY tenant_alert     ON fact_alert          USING (customer_id = current_setting('app.customer_id', true));
-- pipeline roles are BYPASSRLS; the app role sets app.customer_id per connection.

-- ============================================================================
-- CURRENT-STATE VIEWS
-- ============================================================================
CREATE VIEW v_inspection_current AS
    SELECT * FROM fact_inspection WHERE is_current AND record_status = 'ACTIVE';

CREATE VIEW v_gmp_document_current AS
    SELECT * FROM fact_gmp_document WHERE is_current AND record_status = 'ACTIVE';

CREATE VIEW v_warning_letter_current AS
    SELECT * FROM fact_warning_letter WHERE is_current AND record_status = 'ACTIVE';

CREATE VIEW v_enforcement_action_current AS
    SELECT DISTINCT ON (action_id) *
    FROM fact_enforcement_action
    ORDER BY action_id, action_version DESC;               -- retracted actions have operation = 'RETRACT'

CREATE VIEW v_site_identifier_current AS
    SELECT * FROM dim_site_identifier WHERE is_current;

-- U1: every current fact for a site, one row each, with its source id and batch (traceability).
CREATE VIEW v_site_facts AS
    SELECT b.site_key, 'INSPECTION' AS fact_type, i.inspection_id AS fact_id, i.inspection_end_date AS fact_date,
           i.classification AS outcome, 'FDA' AS agency, i.batch_id
      FROM v_site_identifier_current b
      JOIN v_inspection_current i ON b.identifier_type = 'FEI' AND b.identifier_value = i.fei_number
    UNION ALL
    SELECT b.site_key, 'GMP_DOCUMENT', g.doc_ref, g.issued_date, g.status, g.issuing_authority, g.batch_id
      FROM v_site_identifier_current b
      JOIN v_gmp_document_current g ON b.identifier_type = 'EU_SITE_REF' AND b.identifier_value = g.site_ref
    UNION ALL
    SELECT b.site_key, 'WARNING_LETTER', w.letter_id, w.issue_date, w.subject, 'FDA', w.batch_id
      FROM v_site_identifier_current b
      JOIN v_warning_letter_current w ON b.identifier_type = 'LETTER_ID' AND b.identifier_value = w.letter_id
    UNION ALL
    SELECT b.site_key, 'ENFORCEMENT_ACTION', e.action_id, e.effective_date, e.action_type, e.agency, NULL
      FROM v_site_identifier_current b
      JOIN v_enforcement_action_current e ON b.identifier_type = 'FEI' AND b.identifier_value = e.fei_number
     WHERE e.operation <> 'RETRACT';

-- ============================================================================
-- Scale notes
-- ============================================================================
-- Today: ~250k inspections + 60k EU docs + 15y history = low millions of SCD2 rows. No partitioning;
-- the partial indexes on is_current keep "current" reads small.
-- At 10x (25 agencies, 1M sites): LIST-partition fact tables by agency so a re-parse of one agency
-- rewrites one partition; move U4 joins to the Snowflake star.
--
-- If Snowflake were the system of record: same tables, but PK/FK/EXCLUDE are not enforced,
-- partial indexes become CLUSTER BY, RLS becomes row access policies, and merge/split loses
-- single-transaction atomicity.
